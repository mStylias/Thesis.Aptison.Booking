using Synax.EntityFrameworkCore.Abstractions.Ownership;

namespace Aptison.Booking.Domain.Entities.Users;

/// <summary>
/// A person. <see cref="OwnerId"/> is set only on a walk-in, the copy one shop typed in, so the
/// ownership filter shows it to that shop alone; a row with no owner is the person's own and spans
/// companies.
/// </summary>
public class User : SoftDeletableEntity, IHasOptionalOwner<Guid?>
{
    public Guid? OwnerId { get; set; }
    public Company? Owner { get; set; }
    public Guid? KeycloakId { get; set; }
    public string FirstName { get; set; } = null!;
    public string LastName { get; set; } = null!;
    // Null only for a walk-in the shop created without one.
    public string? Email { get; set; }
    public string? PhoneNumber { get; set; }
    public Guid PreferredLanguageId { get; set; }
    public bool IsBanned { get; set; }
    public DateTime? BannedUntil { get; set; }

    /// <summary>Reminder emails only; the booked, changed and cancelled emails ignore it.</summary>
    public bool EmailRemindersEnabled { get; set; } = true;

    /// <summary>Set on a soft-deleted walk-in whose appointments moved to this row.</summary>
    public Guid? MergedIntoId { get; set; }

    /// <summary>
    /// "First Last" lowercased and stripped of accents, generated by the database. Search matches
    /// this, so a term folded any other way misses.
    /// </summary>
    public string NameNormalized { get; private set; } = null!;

    public Language? PreferredLanguageEntity { get; set; }

    /// <summary>The appointments this user booked as the customer.</summary>
    public ICollection<Appointment> Appointments { get; set; } = [];

    /// <summary>At most one per shop; the ownership filter leaves the request's own.</summary>
    public ICollection<CompanyCustomer> CompanyCustomers { get; set; } = [];

    /// <summary>Platform bans and shop blocks, lifted ones included.</summary>
    public ICollection<UserBan> Bans { get; set; } = [];
}
