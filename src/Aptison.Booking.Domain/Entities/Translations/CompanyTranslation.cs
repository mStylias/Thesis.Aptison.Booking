using Synax.EntityFrameworkCore.Abstractions.Core;

namespace Aptison.Booking.Domain.Entities.Translations;

public class CompanyTranslation : IEntity
{
    public Guid CompanyId { get; set; }
    public Company Company { get; set; } = null!;
    public Guid LanguageId { get; set; }
    public Language Language { get; set; } = null!;
    public string Name { get; set; } = null!;
    public string? Description { get; set; }
    public string Street { get; set; } = null!;
    public string? Neighborhood { get; set; }
    public string City { get; set; } = null!;
    public string? Region { get; set; }

    /// <summary>
    /// <see cref="Name"/> lowercased and stripped of accents, generated by the database. Search
    /// matches this and never <see cref="Name"/>, so a term folded any other way misses.
    /// </summary>
    public string NameNormalized { get; private set; } = null!;
}
