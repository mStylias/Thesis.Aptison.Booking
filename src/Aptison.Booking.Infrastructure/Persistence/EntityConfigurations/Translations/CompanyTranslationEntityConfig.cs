using Aptison.Booking.Domain.Entities.Translations;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Aptison.Booking.Infrastructure.Persistence.EntityConfigurations.Translations;

public class CompanyTranslationEntityConfig : IEntityTypeConfiguration<CompanyTranslation>
{
    public void Configure(EntityTypeBuilder<CompanyTranslation> builder)
    {
        builder.ToTable("company_translations");
        builder.HasKey(translation => new { translation.CompanyId, translation.LanguageId });

        builder.Property(translation => translation.Name).HasMaxLength(200);
        builder.Property(translation => translation.Description).HasColumnType("text");
        builder.Property(translation => translation.Street).HasMaxLength(300);
        builder.Property(translation => translation.Neighborhood).HasMaxLength(150);
        builder.Property(translation => translation.City).HasMaxLength(150);
        builder.Property(translation => translation.Region).HasMaxLength(150);

        // Generated by Postgres, never written by EF. The search predicate targets this column, so
        // a term folded any other way silently matches nothing.
        builder.Property(translation => translation.NameNormalized)
            .HasComputedColumnSql("fold(name)", stored: true);

        builder.HasIndex(translation => translation.NameNormalized)
            .HasMethod("gin")
            .HasOperators("gin_trgm_ops")
            .HasDatabaseName("ix_company_translations_name_normalized_trgm");

        builder.HasOne(translation => translation.Company).WithMany(company => company.Translations).HasForeignKey(translation => translation.CompanyId).OnDelete(DeleteBehavior.Cascade);
        builder.HasOne(translation => translation.Language).WithMany().HasForeignKey(translation => translation.LanguageId).OnDelete(DeleteBehavior.NoAction);
    }
}
