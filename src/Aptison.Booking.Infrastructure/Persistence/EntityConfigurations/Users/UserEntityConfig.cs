using Aptison.Booking.Domain.Entities.Users;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Aptison.Booking.Infrastructure.Persistence.EntityConfigurations.Users;

public class UserEntityConfig : IEntityTypeConfiguration<User>
{
    public void Configure(EntityTypeBuilder<User> builder)
    {
        builder.ConfigureEntity("users");
        builder.ConfigureSoftDeletableEntity();

        builder.Property(user => user.FirstName).HasMaxLength(100);
        builder.Property(user => user.LastName).HasMaxLength(100);
        builder.Property(user => user.Email).HasColumnType("citext");
        builder.Property(user => user.PhoneNumber).HasMaxLength(32);
        builder.Property(user => user.IsBanned).HasDefaultValue(false);
        builder.Property(user => user.BannedUntil).HasColumnType("timestamp with time zone");
        builder.Property(user => user.EmailRemindersEnabled).HasDefaultValue(true);

        // Generated by Postgres, never written by EF.
        builder.Property(user => user.NameNormalized)
            .HasComputedColumnSql("fold(first_name || ' ' || last_name)", stored: true);

        builder.HasIndex(user => user.NameNormalized)
            .HasMethod("gin")
            .HasOperators("gin_trgm_ops")
            .HasDatabaseName("ix_users_name_normalized_trgm");

        builder.HasOne(user => user.Owner).WithMany().HasForeignKey(user => user.OwnerId).OnDelete(DeleteBehavior.NoAction);
        builder.HasOne<User>().WithMany().HasForeignKey(user => user.MergedIntoId).OnDelete(DeleteBehavior.NoAction);

        builder.HasOne(user => user.PreferredLanguageEntity)
            .WithMany()
            .HasForeignKey(user => user.PreferredLanguageId)
            .OnDelete(DeleteBehavior.NoAction);

        builder.HasIndex(user => user.KeycloakId)
            .IsUnique()
            .HasDatabaseName("ux_users_keycloak_id")
            .HasFilter("keycloak_id IS NOT NULL AND NOT is_deleted");

        builder.HasIndex(user => user.Email)
            .IsUnique()
            .HasDatabaseName("ux_users_email")
            .HasFilter("owner_id IS NULL AND email IS NOT NULL AND NOT is_deleted");

        builder.HasIndex(user => new { user.OwnerId, user.Email })
            .IsUnique()
            .HasDatabaseName("ux_users_owner_email")
            .HasFilter("owner_id IS NOT NULL AND email IS NOT NULL AND NOT is_deleted");

        builder.HasIndex(user => user.PhoneNumber)
            .HasDatabaseName("ix_users_phone_number")
            .HasFilter("phone_number IS NOT NULL AND NOT is_deleted");
    }
}
