def add_pool(shop, people, history_days, walk_in=False):
    for p in people:
        weight = min(math.exp(rng.gauss(0, 0.6)), 3.0) * (0.6 if walk_in else 1.0)
        start = -history_days + int((history_days - 3) * (rng.random() ** 2.4))
        end = start + rng.randint(45, 400) if rng.random() < 0.22 and history_days > 120 else None
        if end is not None and end > -10:
            end = None
        pools.append((shop, p, round(weight, 4), start, end, rng.random() < 0.025))


