def uid(key: str) -> str:
    m = hashlib.md5(('seed:' + key).encode()).hexdigest()
    return f'{m[0:8]}-{m[8:12]}-4{m[13:16]}-{"89ab"[int(m[16], 16) % 4]}{m[17:20]}-{m[20:32]}'


def q(value) -> str:
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def ago(days: float) -> str:
    return f"now() - interval '{round(days * 86400)} seconds'"


def ascii_slug(text: str) -> str:
    text = unicodedata.normalize('NFKD', text.replace("'", '')).encode('ascii', 'ignore').decode().lower()
    return re.sub(r'[^a-z0-9]+', '-', text).strip('-')


