def new_phone() -> str:
    while True:
        phone = '+3069' + str(rng.randint(10_000_000, 99_999_999))
        if phone not in used_phones:
            used_phones.add(phone)
            return phone


def new_email(first_en: str, last_en: str) -> str:
    base = f'{ascii_slug(first_en)}.{ascii_slug(last_en)}'.replace('-', '')
    email, n = f'{base}@{DOMAIN}', 2
    while email in used_emails:
        email, n = f'{base}{n}@{DOMAIN}', n + 1
    used_emails.add(email)
    return email


def make_person(gender: str, *, first=None, last=None, email=None, phone='auto', lang='el'):
    if first is None:
        f = rng.choice(male_first if gender == 'm' else female_first)
        s = rng.choice(surnames)
        first, last = (f['el'], f['en']), (s['m_el'], s['m_en']) if gender == 'm' else (s['f_el'], s['f_en'])
    if email is None:
        email = new_email(first[1], last[1])
    else:
        used_emails.add(email)
    if phone == 'auto':
        phone = new_phone()
    return {
        'id': uid('user:' + email), 'first_el': first[0], 'first_en': first[1], 'last_el': last[0],
        'last_en': last[1], 'email': email, 'phone': phone, 'gender': gender, 'lang': lang,
        'login': True, 'owner': None,
    }


